/**
 * Перевод MCP-проекции `fields` в query-параметр `fields` Entity API.
 *
 * ЖИВАЯ ПРОБА 2026-08-20: Entity API отдаёт содержательные поля записи
 * (`summary` и прочие) в объекте `fields` ТОЛЬКО когда запрошены явно —
 * `?fields=summary`. Без этого ответ состоит из служебных полей
 * (`id`/`shortId`/`version`/`entityType`/даты), а MCP-проекция `fields`
 * применялась клиентски поверх ответа, в котором нужных полей и не было:
 * `fields.summary` всегда приходил пустым, то есть цели и проекты через
 * типизированные инструменты были безымянными.
 *
 * Запрашиваем ровно то, что попросил агент: элементы проекции вида
 * `fields.<name>`. Имя, которого в Трекере нет, API отвергает явной 422
 * («поля [x] не существуют») — это честнее тихо пустого ответа.
 *
 * Голый `fields` без имени (легальная форма проекции «отдай весь вложенный
 * объект», см. `ResponseFieldFilter`) выполнить нельзя: способа запросить у
 * Entity API все поля разом нет — `fields=*` и `fields=all` отвергаются той же
 * 422 (проверено живьём 2026-08-20). Молча вернуть пустоту здесь означало бы
 * воспроизвести ровно тот дефект, который этот файл и чинит, поэтому такая
 * проекция отклоняется явной ошибкой с указанием, что делать.
 */

const FIELDS_PREFIX = 'fields.';

/**
 * Выбрать имена полей Entity API из MCP-проекции.
 *
 * @param projection - значения параметра `fields` MCP-инструмента
 * @returns имена полей для `?fields=` без дублей; пустой массив, если
 *          содержательные поля не запрашивались
 * @throws {Error} если запрошен голый `fields` без имени конкретного поля
 */
export function extractEntityApiFields(projection: readonly string[]): string[] {
  if (projection.includes('fields')) {
    throw new Error(
      'Entity API не умеет отдавать все поля записи разом, поэтому проекция "fields" целиком ' +
        'не поддерживается: перечисли нужные поля поимённо, например "fields.summary". ' +
        'Имена — это идентификаторы полей Трекера (см. get_global_fields).'
    );
  }

  const names = projection
    .filter((entry) => entry.startsWith(FIELDS_PREFIX))
    .map((entry) => entry.slice(FIELDS_PREFIX.length).split('.')[0] ?? '')
    .filter((name) => name.length > 0);

  return [...new Set(names)];
}
