/**
 * Санитайзер текста, приходящего из Трекера (пакет 6.1 — пилот MCP Apps №1).
 *
 * `description` задачи — недоверенный ввод: его пишут пользователи Трекера,
 * и он попадает в HTML-виджет (`ui://tracker/issue-description-editor`),
 * рендерящийся в песочном iframe хоста. Хотя виджет и так вставляет текст
 * ТОЛЬКО через `textContent`/`.value` (см. `issue-description-editor.widget.ts`)
 * — что само по себе не исполняет разметку — это единственный уровень защиты
 * недостаточен как контракт: любой будущий код (в этом файле или в другом
 * потребителе того же `structuredContent`, включая fallback-текст для
 * клиентов без Apps) может по ошибке начать использовать `innerHTML`. Поэтому
 * сама СТРОКА, уходящая в `structuredContent`, уже не содержит HTML-тегов —
 * защита на границе данных, а не только на границе рендера.
 *
 * Стратегия — вырезать, а не экранировать: `description` в Трекере — это YFM
 * (markdown-подобная разметка), не HTML, поэтому легитимный текст не содержит
 * `<...>`-последовательностей вообще. Всё, что похоже на HTML-тег, считается
 * потенциальной атакой (вставленный пользователем `<script>`/`<img onerror>`)
 * и удаляется целиком, а не превращается в `&lt;...&gt;` — экранирование
 * оставило бы код читаемым, но не изменило бы того факта, что автор описания
 * пытался вставить разметку, которую мы не рендерим как разметку.
 */

const SCRIPT_BLOCK_PATTERN = /<script[^>]*>[\s\S]*?<\/script>/gi;
const STYLE_BLOCK_PATTERN = /<style[^>]*>[\s\S]*?<\/style>/gi;
const ANY_TAG_PATTERN = /<[^>]*>/g;

/**
 * Убирает HTML-теги (включая содержимое `<script>`/`<style>` целиком) и
 * нормализует переводы строк/пробелы по краям. Безопасно для plain-text
 * контекстов (JSON `structuredContent`, `content[0].text`, `.value` textarea
 * в виджете) — на выходе гарантированно нет `<`/`>`.
 */
export function sanitizeTrackerText(input: string): string {
  return input
    .replace(SCRIPT_BLOCK_PATTERN, '')
    .replace(STYLE_BLOCK_PATTERN, '')
    .replace(ANY_TAG_PATTERN, '')
    .replace(/\r\n/g, '\n')
    .trim();
}
