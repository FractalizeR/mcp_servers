/**
 * Zod-билдер схемы идентификатора числовых сущностей Яндекс.Трекера
 * (доска, колонка доски, спринт, компонент), приходящего от вызывающего агента.
 *
 * ВАЖНО: API v3 отдаёт `id` этих сущностей числом (`Board.id`, `BoardColumn.id`,
 * `Sprint.id`, `Component.id` — см. entities), но агент получает это число из
 * ответа одного инструмента и должен передать его АРГУМЕНТОМ в другой (например,
 * `get_boards` → `get_board`). Схема входа обязана принимать то же значение, что
 * пришло в ответе, — и строкой, и числом, — иначе цепочка вызовов рвётся на
 * валидации там, где по смыслу вызов корректен. Пути запроса строятся
 * интерполяцией строки, поэтому внутри инструмента тип остаётся `string`.
 */

import { z } from 'zod';

/**
 * Строит схему идентификатора сущности: принимает строку или целое число,
 * приводит результат к строке. Обратная совместимость не страдает — то, что
 * принималось строкой, продолжает приниматься.
 *
 * @param entityLabel — именительный падеж, используется в сообщении об ошибке
 *   и в `.describe()` (например, «Board», «Sprint», «Column»)
 */
export function buildEntityIdSchema(entityLabel: string): z.ZodType<string> {
  return z
    .union([z.string().min(1, `${entityLabel} ID не может быть пустым`), z.number().int()], {
      error: () => `${entityLabel} ID должен быть строкой или целым числом`,
    })
    .transform((value) => String(value))
    .describe(
      `Идентификатор (${entityLabel} ID) — строка или число, обе формы принимаются ` +
        '(API возвращает его числом, но допускается и строковое представление)'
    );
}
