/**
 * DTO для управления доступом к очереди в Яндекс.Трекере
 *
 * Документированная форма тела (api-ref/queues/manage-access, раздел «Параметры
 * тела запроса»): `{ <разрешение>: { users|groups|roles: [...] | { add|remove: [...] } } }`.
 * Прежняя форма `{ <роль>: { <действие>: [субъекты] } }` (роли `queue-lead`,
 * `team-member`, `follower`, `access`) не документирована и живой пробой
 * 2026-08-26 отклонена API на всех четырёх ролях (`400 <роль>: Incorrect data
 * format`) — контракт переписан целиком.
 */

/**
 * Разрешение — единственный ключ верхнего уровня тела запроса.
 * `deny` допускает только `subjectKind: 'users' | 'groups'` — ролям запретить
 * доступ нельзя (документация, раздел «Параметры тела запроса»).
 */
export type QueueAccessPermission = 'create' | 'write' | 'read' | 'grant' | 'deny';

/** Вид субъекта: пользователь, группа (числовой id) или встроенная роль задачи. */
export type QueueAccessSubjectKind = 'users' | 'groups' | 'roles';

/** Действие над списком субъектов. */
export type AccessAction = 'add' | 'remove';

/**
 * Встроенные роли задачи, доступные как субъект (`subjectKind: 'roles'`).
 * `queue-lead` сюда не входит: документация «Допустимые идентификаторы» не
 * объявляет его назначаемой ролью — он встречается только в ответах API.
 */
export type QueueAccessRoleSubject = 'author' | 'assignee' | 'follower' | 'access';

/**
 * DTO для управления правами доступа к очереди.
 *
 * Форма «одно разрешение × один вид субъекта × одно действие за запрос» — осознанное
 * сужение документированной мультиформы (несколько разрешений в одном теле, а также
 * форма-замена `users: [...]` без `add`/`remove`). Причина сужения — предсказуемость
 * инструмента для агента: один вызов производит один понятный эффект, а не набор
 * параллельных.
 */
export interface ManageQueueAccessDto {
  /** Разрешение, которым управляем */
  permission: QueueAccessPermission;

  /** Вид субъекта: пользователи, группы (числовой id) или роли задачи */
  subjectKind: QueueAccessSubjectKind;

  /** Массив ID пользователей, ЧИСЛОВЫХ id групп либо идентификаторов ролей */
  subjects: (string | number)[];

  /** Действие: добавить или удалить */
  action: AccessAction;
}
