/**
 * Типы реестра сознательных исключений из покрытия (план
 * `.agentic-planning/plan_tracker_test_coverage/2.1.1_matrix_and_harness_sequential.md`
 * §C). Реестр — не Markdown: его читает `scripts/build-coverage-matrix.ts`, и рассинхрон
 * таблицы с кодом — тот самый класс дефекта, который весь этап 2.1 закрывает.
 */

/** Свойство исправного инструмента (`packages/servers/TESTING_STRATEGY.md` §1). */
export type CoverageProperty = 'С-1' | 'С-2' | 'С-3' | 'С-4' | 'С-5' | 'С-6' | 'С-7';

/** Единственный источник перечня `CoverageProperty` для рантайм-валидации (M-9). */
export const COVERAGE_PROPERTIES: readonly CoverageProperty[] = [
  'С-1',
  'С-2',
  'С-3',
  'С-4',
  'С-5',
  'С-6',
  'С-7',
];

export interface CoverageException {
  /** Базовое имя инструмента без префикса сервера (например, `create_queue`). */
  readonly tool: string;
  /** Свойство, которое сознательно не проверяется на уровне интеграционных тестов. */
  readonly property: CoverageProperty;
  /** Почему свойство не проверяется здесь — с точной ссылкой (файл, раздел). */
  readonly reason: string;
  /**
   * Чем свойство фактически подтверждается взамен (уровень + путь к тесту), либо
   * `null`, если сейчас ничем (в этом случае `reason` обязана объяснять, почему это
   * приемлемо, а не просто «пока не сделано»).
   */
  readonly replacedBy: string | null;
}

/**
 * Свойства, про которые живой прогон вообще способен что-то сказать: верность
 * маршрута и правдивость эффекта. Остальные пять свойств живой прогон не наблюдает —
 * С-1/С-7 живут на другом уровне, С-2/С-3/С-6 наблюдает мок, и запись реестра живых
 * наблюдений на них означала бы не наблюдение, а путаницу уровней.
 */
export type LiveObservableProperty = Extract<CoverageProperty, 'С-4' | 'С-5'>;

/** Единственный источник перечня `LiveObservableProperty` для рантайм-валидации. */
export const LIVE_OBSERVABLE_PROPERTIES: readonly LiveObservableProperty[] = ['С-4', 'С-5'];

/**
 * Свойство инструмента, наблюдавшееся в живом прогоне.
 *
 * Заменяет категорийное «живьём не наблюдается никогда»: прежний список из шести
 * папок `src/tools/api/*` задавал посылку сразу 36 инструментам, а прогоны 25 и 26
 * августа наблюдали доски, спринты, фильтры и очереди живьём — заметить устаревшую
 * посылку было нечем, потому что записать факт живого наблюдения было некуда.
 */
export interface LiveObservation {
  /** Базовое имя инструмента без префикса сервера (например, `update_board`). */
  readonly tool: string;
  readonly property: LiveObservableProperty;
  /** Метка прогона (`YANDEX_TRACKER_LIVE_SCOPE_RUN_ID`), например `sweep7-2026-08-26`. */
  readonly runLabel: string;
  /** Путь к отчёту прогона от корня пакета — обязан существовать на диске. */
  readonly report: string;
  /**
   * Что именно прочитано ОБРАТНО, независимым чтением. Код ответа наблюдением не
   * является: инструмент, отчитавшийся об успехе и ничего не изменивший, для
   * проверки «ответ выглядит правильно» невидим (канон §3). Именно эта подмена
   * завела всю серию дефектов маршрутов, поэтому поле обязательно и непусто.
   *
   * Требование действует поэлементно, а не на запись целиком: клауза вида
   * «`start` спринта `238` — 200» критерию не удовлетворяет, даже если соседние
   * клаузы той же записи несут обратное чтение. Машинно это не проверяется —
   * эвристика «в клаузе только код ответа» отделить «200 и версия 1→2» от
   * «200» может только по смыслу, — поэтому клаузы сверяет ревью реестра.
   */
  readonly readBack: string;
  /**
   * Отпечаток схемы параметров инструмента (`computeToolSchemaFingerprint`,
   * `@fractalizer/mcp-core`) на момент наблюдения. Обязателен и непуст.
   *
   * Без него запись — утверждение, которое нельзя просрочить: клетка `живьём`
   * оставалась зелёной после любой правки инструмента. Расхождение отпечатка
   * роняет `coverage:check` (`scripts/build-coverage-matrix.ts`) с требованием
   * либо перепроверить инструмент живьём, либо пере-штамповать запись.
   *
   * Чего отпечаток НЕ ловит — двух вещей, а не одной:
   * - **маршрут** живёт в операции API, и его смена (URL, метод, форма тела
   *   запроса) без смены схемы инструмента этим полем не видна;
   * - **форма ответа** (`outputSchema`, DTO разбора) в отпечаток не входит вовсе,
   *   а С-5 — правдивость эффекта — читается именно через ответ. Это не
   *   гипотетический класс: прогон 26 августа вскрыл ровно его —
   *   `PATCH .../permissions` отвечает `{self, version}`, а `QueuePermissionsOutput`
   *   объявлял массив, и типизация «по документации» роняла бы каждый успешный
   *   вызов (`tests/live-runs/0_LIVE_RUN_REPORT_2026-08-26.md`, раздел «Форма
   *   ответа `PATCH .../permissions`»). Переобъявление выходного DTO сегодня не
   *   гасит ни одной клетки `живьём`.
   *
   * См. JSDoc `tool-schema-fingerprint.ts` и `tests/TESTING_STRATEGY.md` §1.
   */
  readonly schemaFingerprint: string;
  /**
   * Заполняется, только когда отпечаток проставлен НЕ от кода на момент
   * наблюдения, а от более позднего: схему правили после прогона, и запись
   * пере-штампована вместо повторной живой пробы.
   *
   * Отдельное поле, а не фраза в `readBack`, ровно затем, чтобы пере-штамповка
   * была отличима от свежего наблюдения в диффе и в матрице: без него
   * единственный дешёвый выход из расхождения (правка 12 hex-символов) не
   * оставлял следа вообще.
   *
   * Поле — МАРКЕР ДЛЯ РЕВЬЮ, а не принуждение: правка `schemaFingerprint` БЕЗ
   * добавления этого поля остаётся законным входом, потому что связать одно с другим
   * машинно можно только сравнением с git-предком файла. Барьер здесь — дифф и ревью,
   * и называть это иначе значило бы завести ровно то утверждение о несуществующей
   * проверке, против которого поле и заведено.
   */
  readonly fingerprintRestamp?: FingerprintRestamp;
}

export interface FingerprintRestamp {
  /**
   * Коммит, изменивший схему после прогона, — чтобы правку можно было прочитать.
   * Обязателен и непуст; дополнительно проверяется ФОРМА — 7–40 hex-символов, как у
   * короткого хеша git. Существование коммита в репозитории НЕ проверяется: валидация
   * реестра не ходит в git (тесты гоняются и на выгрузке без истории), поэтому
   * «коммит есть в этой ветке» остаётся на ревью.
   */
  readonly afterCommit: string;
  /** Почему прежнее наблюдение эту правку пережило. Обязательно и непусто. */
  readonly why: string;
}

/**
 * Живое наблюдение СНЯТО сознательно: контракт инструмента изменился так, что
 * прежнее наблюдение к нему не относится, а повторить прогон сейчас нечем.
 *
 * Заведено потому, что из расхождения отпечатка не было честного выхода. Первый
 * (перепроверить живьём) требует боевого прогона под токеном; второй
 * (пере-штамповка) годится, только когда обоснование есть; третий — признать, что
 * наблюдение относится к другой версии контракта, и убрать его — был механически
 * заблокирован: клетка становится `не наблюдалось`, гейт покрытия видит новую дыру
 * и печатает «у инструмента потеряли тест», что неверно по существу.
 *
 * Запись делает третий выход законным и НЕ ослабляет храповик: строку в
 * `COVERAGE_GATE_BASELINE` разрешено дописать только вместе с записью на ту же пару, и
 * `coverage:check` сверяет это машинно — по замороженному снимку
 * `COVERAGE_GATE_BASELINE_ORIGIN` (ключ вне снимка и без записи о снятии роняет
 * прогон). Без записи дописанная строка по-прежнему означает «потеряли тест».
 *
 * Строка базлайна нужна ТОЛЬКО для свойств из `GATED_PROPERTIES` (сегодня это С-4 из
 * двух живо наблюдаемых). Снятие наблюдения по С-5 клетку гейта не создаёт, и строка
 * `tool[С-5]` в базлайне немедленно становится нарушением `closed`.
 */
export interface RetiredLiveObservation {
  readonly tool: string;
  readonly property: LiveObservableProperty;
  /** Метка снятого прогона — чтобы было видно, какое именно наблюдение снято. */
  readonly runLabel: string;
  /** Отчёт снятого прогона; остаётся на диске, иначе снятие нечем прочитать. */
  readonly report: string;
  /** Почему наблюдение больше не относится к текущему контракту. */
  readonly reason: string;
  /** Какая проба вернёт клетку в `живьём`. */
  readonly whatWouldClose: string;
}

/**
 * Живой прогон этого свойства не достигает — с условием, которое запись снимет.
 *
 * `whatWouldClose` обязательно и непусто: запись без условия закрытия живёт вечно,
 * чем и была категорийная посылка.
 */
export interface LiveUnreachable {
  readonly tool: string;
  readonly property: LiveObservableProperty;
  /** Почему живой прогон недостижим — с точной ссылкой (файл, раздел, дефект). */
  readonly reason: string;
  /** Какая проба снимет эту запись. */
  readonly whatWouldClose: string;
  /** Путь к отчёту прогона, где недостижимость наблюдалась, — обязан существовать. */
  readonly report: string;
}
