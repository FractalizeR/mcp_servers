/**
 * Отпечаток схемы параметров инструмента — способ привязать утверждение,
 * записанное о инструменте однажды, к состоянию его кода.
 *
 * Заведён для реестра живых наблюдений yandex-tracker
 * (`tests/coverage-exceptions/live-observations.ts`): запись «наблюдалось
 * живьём» ничем не была привязана к коду, и клетка матрицы оставалась зелёной
 * после любой правки инструмента — утверждение, которое нельзя просрочить.
 *
 * **Что отпечаток ловит:** любое изменение состава, типов, описаний,
 * значений по умолчанию и ограничений схемы параметров — то есть контракта,
 * который инструмент показывает вызывающему.
 *
 * **Чего отпечаток НЕ ловит** (граница названа здесь, чтобы совпадение
 * отпечатков не читалось шире, чем оно есть) — изменения ЗА пределами схемы
 * параметров, и таких классов ДВА:
 * - **маршрут** (URL, метод, форма тела запроса) живёт в операции API, и его
 *   смена без смены схемы инструмента отпечатком не видна;
 * - **форма ОТВЕТА** — `outputSchema` и DTO разбора ответа в отпечаток не
 *   входят вовсе. Умалчивать об этом нельзя: утверждение «эффект правдив»
 *   читается именно через ответ, и класс не гипотетический — живой прогон
 *   yandex-tracker 26.08.2026 вскрыл `PATCH .../permissions`, отвечающий
 *   `{self, version}` при типе, объявлявшем массив: типизация «по
 *   документации» роняла бы каждый успешный вызов. Переобъявление выходного
 *   DTO сегодня не гасит ни одной записи.
 *
 * Отвергнут вариант «хэш исходников инструмента и операции»: он полон, но
 * гасит запись от правки комментария, а барьер, который дорого соблюдать,
 * начинают обходить штамповкой не глядя. Включение `outputSchema` в отпечаток
 * не отвергнуто, а отложено: цена — записи гаснут от правок проекции ответа,
 * и решение принимается владельцем реестра, а не здесь.
 *
 * **Названный риск: дрейф генератора.** Отпечаток считается не от исходника
 * zod-схемы, а от результата её конвертации, то есть зависит от адаптера
 * zod→JSON Schema и от версии `zod`. Обновление любого из них меняет отпечатки
 * ВСЕХ записей разом, а механизм не отличает «изменился контракт этого
 * инструмента» от «изменился генератор у всех». Массовая пере-штамповка в этом
 * случае была бы ложью: она записала бы «наблюдение правку контракта пережило»
 * там, где контракт не менялся вовсе, и заодно проштамповала бы те записи, чей
 * контракт в это же время действительно уехал. Порядок ключей нейтрализован
 * `stableStringify`, порядок элементов массивов (`required`, `enum`, `anyOf`) —
 * нет и намеренно значим. Правильная реакция на массовое расхождение —
 * разбираться с причиной, а не штамповать; отличать причины машинно (например,
 * отдельным отпечатком версии генератора на весь реестр) — незакрытый вопрос.
 */

import { createHash } from 'node:crypto';
import type { ToolDefinition } from './base.types.js';
import { readToolInputSchema } from './tool-input-schema.js';
import type { ToolClassLike } from './tool-input-schema.js';

/**
 * Длина отпечатка в hex-символах. Коротко ровно затем, чтобы строка читалась в
 * диффе реестра глазами. Коллизии моделью угроз здесь не являются: отпечаток
 * защищает от НЕЗАМЕЧЕННОГО дрейфа схемы, а не от подделки — подобрать схему
 * под чужой отпечаток проще правкой самой записи реестра, которая и так лежит
 * рядом в том же файле.
 */
const FINGERPRINT_LENGTH = 12;

/**
 * Сериализация со стабильным порядком ключей: два объекта с одинаковым
 * содержимым и разным порядком ключей обязаны дать одну строку, иначе
 * отпечаток менялся бы от перестановки полей в генераторе схемы.
 *
 * `undefined` в значениях объекта опускается — так же, как это делает
 * `JSON.stringify`; ключ с `undefined` и отсутствующий ключ для схемы
 * неразличимы.
 */
function stableStringify(node: unknown): string {
  if (Array.isArray(node)) {
    return `[${node.map((item) => stableStringify(item)).join(',')}]`;
  }
  if (typeof node === 'object' && node !== null) {
    const entries = Object.entries(node as Record<string, unknown>)
      .filter(([, value]) => value !== undefined)
      .sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0))
      .map(([key, value]) => `${JSON.stringify(key)}:${stableStringify(value)}`);
    return `{${entries.join(',')}}`;
  }
  return JSON.stringify(node) ?? 'null';
}

/** Отпечаток произвольной схемы — отдельно от чтения класса, чтобы детерминизм проверялся тестом напрямую. */
export function computeSchemaFingerprint(schema: unknown): string {
  return createHash('sha256')
    .update(stableStringify(schema), 'utf8')
    .digest('hex')
    .slice(0, FINGERPRINT_LENGTH);
}

/**
 * Отпечаток схемы параметров инструмента.
 *
 * Схема берётся тем же единственным способом, что и у барьера допусков, —
 * `readToolInputSchema`; бросок при нечитаемой схеме уходит наверх, чтобы
 * вызывающий барьер отказал, а не проштамповал пустоту.
 */
export function computeToolSchemaFingerprint(ToolClass: ToolClassLike): string {
  const inputSchema: ToolDefinition['inputSchema'] = readToolInputSchema(ToolClass);
  return computeSchemaFingerprint(inputSchema);
}
