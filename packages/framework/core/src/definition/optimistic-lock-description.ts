/**
 * Единая формулировка подсказки об оптимистичной блокировке для описаний
 * параметров (`.describe()`).
 *
 * Профилактика работает только ДО вызова: описание параметра модель читает,
 * формируя аргументы, тогда как предупреждение `VERSION_NOT_PROVIDED` приходит,
 * когда запись уже применена и перезапись предотвратить нечем.
 *
 * Текст один на все инструменты обоих серверов намеренно: разойдись
 * формулировка риска по копиям — разойдётся и поведение модели, а дублирование
 * такой длины ниже порога `cpd` и молча переживёт правку одной из копий.
 *
 * Здесь собирается ТОЛЬКО неизменная часть — риск. Где взять токен, знает
 * вызывающий: у Трекера токен приходит клиентской проекцией `fields`, у Вики
 * он базовое поле ответа, и зашитая сюда клауза про `fields` оказалась бы
 * ложью для одного из двух серверов.
 */

/** Имя поля-токена в сущностях API обоих серверов. */
export type OptimisticLockParamName = 'version' | 'revision';

/**
 * Что происходит при конфликте. Различает НАБЛЮДЁННОЕ поведение API, а не форму
 * поля схемы: параметр может быть обязателен в схеме, а исход при конфликте —
 * не проверен ни одной живой пробой.
 */
export type OptimisticLockConflict =
  /**
   * Правка применяется поверх чужой: «последний выигрывает». Ставится, когда
   * исход подтверждён живой пробой самого инструмента либо другого инструмента
   * ТОГО ЖЕ контракта записи.
   */
  | 'silent-overwrite'
  /**
   * Исход не наблюдался и по соседям не выводится (другой API, другая
   * семантика) — ничего про него не обещаем.
   */
  | 'unspecified';

export interface OptimisticLockDescriptionOptions {
  readonly paramName: OptimisticLockParamName;
  /**
   * Клауза «где взять значение» целиком, включая нужную серверу механику
   * («в ответе get_issues/find_issues — запроси его в fields»).
   */
  readonly source: string;
  readonly conflict: OptimisticLockConflict;
  /**
   * Оговорка области применения. Встаёт ПЕРЕД риском: у инструмента, где токен
   * запрещён для части действий, совет «передавай» обязан быть прочитан уже
   * суженным, иначе описание читается как противоречащее само себе.
   */
  readonly lead?: string;
}

/**
 * «Может перезаписать», а не «перезапишет»: перезапись случится только при
 * реальной параллельной правке — обещать её в каждом вызове значит приучать
 * читателя не верить тексту.
 */
export function buildOptimisticLockDescription(options: OptimisticLockDescriptionOptions): string {
  const { paramName, source, conflict, lead } = options;

  const risk =
    conflict === 'silent-overwrite'
      ? 'Токен оптимистичной блокировки: без него правка может незаметно перезаписать чужие параллельные изменения.'
      : 'Токен оптимистичной блокировки: передавай актуальное значение, чтобы правка не легла поверх чужой.';

  const prefix = lead === undefined ? '' : `${lead} `;

  return `${prefix}${risk} Значение — поле ${paramName} ${source}.`;
}
