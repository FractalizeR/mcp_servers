/**
 * Объявление пишущего прогона дочернему серверу.
 *
 * `--dangerously-allow-write` снимает блокировку на стороне dev-клиента, но сам
 * сервер об этом не знает — и не может потребовать собственных мер безопасности
 * именно для пишущего прогона. Маркер закрывает этот разрыв: клиент сообщает
 * «этот прогон разрешает запись», а что из этого следует, решает сервер.
 *
 * Домен-агностично намеренно: dev-клиент общий для всех серверов монорепо и не
 * знает ни про очереди Трекера, ни про пространства Вики. Сервер, у которого
 * защиты нет, маркер просто игнорирует.
 */

/** Имя переменной окружения дочернего процесса. */
export const WRITE_DECLARATION_VAR = 'MCP_DEV_WRITE_ALLOWED';

/** Значение маркера; проверять следует именно его, а не факт наличия ключа. */
export const WRITE_DECLARATION_VALUE = '1';

/** Добавляет объявление к окружению, если прогон разрешает запись. */
export function declareWriteRun(
  env: Record<string, string>,
  allowWrite: boolean
): Record<string, string> {
  if (!allowWrite) return env;
  return { ...env, [WRITE_DECLARATION_VAR]: WRITE_DECLARATION_VALUE };
}
