/**
 * Надзор за исходящим HTTP-трафиком клиента.
 *
 * Домен-агностичен: инфраструктура не знает, что считается допустимой областью
 * действия, — решение принимает сервер. Здесь только точки, в которых это решение
 * исполняется, и они выбраны так, что обойти их нельзя: перехват стоит на самом
 * axios instance, а не на методах `IHttpClient`. Операции, отправляющие multipart
 * и бинарные тела, берут instance напрямую через `getAxiosInstance()` — рубеж на
 * уровне `IHttpClient` не увидел бы именно их.
 */

/** Исходящий запрос в том виде, в каком его видит guard — до отправки. */
export interface OutgoingRequest {
  /** HTTP-метод в нижнем регистре ('get', 'post', 'patch', 'delete', ...). */
  method: string;

  /** Путь запроса относительно baseURL, вместе с query-строкой. */
  url: string;

  /** Тело запроса как его сформировал axios: JSON-строка, FormData или undefined. */
  data: unknown;
}

/** Ответ на разрешённый запрос — источник идентификаторов созданных сущностей. */
export interface ObservedResponse {
  /** Запрос, на который пришёл этот ответ. */
  request: OutgoingRequest;

  /** HTTP-статус ответа. */
  status: number;

  /** Тело ответа после разбора axios. */
  data: unknown;
}

export interface HttpTrafficGuard {
  /**
   * Решение по запросу до отправки. Отказ выражается броском исключения;
   * возврат означает разрешение.
   *
   * Обязана быть синхронной: асинхронная проверка пропустила бы запрос, пока думает.
   */
  inspectRequest(request: OutgoingRequest): void;

  /**
   * Наблюдение ответа на разрешённый запрос. Не влияет на его исход — бросок здесь
   * превратил бы удавшуюся мутацию в видимую ошибку, оставив эффект в системе.
   */
  observeResponse(response: ObservedResponse): void;
}
