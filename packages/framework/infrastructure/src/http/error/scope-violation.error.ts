/**
 * Отказ надзора за областью действия: запрос не ушёл в сеть.
 *
 * Отдельный тип, а не обычная `Error`, по двум причинам, каждая из которых уже
 * проявлялась на этом коде:
 * - `ErrorMapper` относит любую ошибку без ответа сервера к сетевым (`statusCode 0`),
 *   а сетевая ошибка входит в набор «исход неопределён» и повторяется — отказ guard
 *   превращался в четыре попытки вместо одной;
 * - в тексте ошибки должно быть видно, что запрос отклонён СВОИМ рубежом, а не сетью:
 *   иначе диагностика живого прогона уводит в сторону сети.
 */
export class ScopeViolationError extends Error {
  /** Повтор бессмыслен: отказ детерминирован и не зависит от состояния сети. */
  readonly retryable = false;

  constructor(message: string) {
    super(message);
    this.name = 'ScopeViolationError';
  }
}
