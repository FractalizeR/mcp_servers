/**
 * Интерфейс стратегии повтора запросов
 *
 * Ответственность (SRP):
 * - Определение, нужно ли повторять запрос
 * - Вычисление задержки перед следующей попыткой
 */

import type { ApiError } from '../../types.js';

/** HTTP-методы, для которых применяется retry-политика. */
export type HttpMethod = 'get' | 'post' | 'patch' | 'delete';

/**
 * Контекст запроса, необходимый стратегии для решения о повторе.
 *
 * `idempotencyDeclared` — явное объявление вызывающей стороной, что КОНКРЕТНЫЙ
 * POST-запрос идемпотентен (например, снабжён ключом идемпотентности, который
 * сервер учитывает при повторе и не создаёт дубль вместо второго объекта).
 * Для методов, отличных от `post`, игнорируется — GET/PATCH/DELETE считаются
 * безопасными для повтора, как и раньше.
 */
export interface RetryContext {
  readonly method: HttpMethod;
  readonly idempotencyDeclared?: boolean;
}

export interface RetryStrategy {
  /**
   * Определяет, нужно ли повторять запрос при данной ошибке.
   *
   * ВАЖНО: решение зависит не только от статус-кода, но и от метода запроса.
   * Неидемпотентный POST при ошибке с неопределённым исходом (сеть, таймаут,
   * 5xx) мог уже быть выполнен сервером — повтор создаст дубль. Поэтому такие
   * POST повторяются только если `idempotencyDeclared === true`, либо если
   * статус — 429 (сервер сам просит повторить, запрос заведомо не выполнялся).
   *
   * @param context - метод запроса и признак объявленной идемпотентности
   * @param error - ошибка API
   * @param attempt - номер текущей попытки (начиная с 0)
   * @returns true, если запрос нужно повторить
   */
  shouldRetry(context: RetryContext, error: ApiError, attempt: number): boolean;

  /**
   * Вычисляет задержку перед следующей попыткой (в миллисекундах)
   * @param attempt - номер текущей попытки (начиная с 0)
   * @param error - опциональная ошибка (для специальной обработки, например 429)
   * @returns задержка в миллисекундах
   */
  getDelay(attempt: number, error?: ApiError): number;

  /**
   * Максимальное количество попыток
   */
  readonly maxRetries: number;

  /**
   * Является ли исход запроса при данной ошибке НЕОПРЕДЕЛЁННЫМ — то есть мог ли
   * сервер фактически выполнить операцию, несмотря на ошибку в ответе (сеть,
   * таймаут, 5xx, 429), в противовес ошибкам, при которых сервер заведомо не
   * выполнял операцию (400, 404 и т.п.).
   *
   * Используется `RetryHandler` для формулировки предупреждения при отказе
   * от повтора неидемпотентного POST — только такие ошибки требуют подсказки
   * «операция могла выполниться, проверьте перед повтором».
   *
   * @param error - ошибка API
   * @returns true, если исход запроса неопределён
   */
  isOutcomeAmbiguous(error: ApiError): boolean;
}
